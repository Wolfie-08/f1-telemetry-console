/**
 * Trace an outline from raw /location rows (any circuit, any session).
 * Drops null samples and the long straight-line jumps that appear when the
 * transponder drops out.
 */
export function deriveOutline(rows) {
  const pts = []
  let prev = null
  for (const r of rows) {
    if (r.x == null || r.y == null) continue
    if (r.x === 0 && r.y === 0) continue
    if (prev) {
      const d = Math.hypot(r.x - prev[0], r.y - prev[1])
      if (d > 2500) continue          // teleport => dropout, skip
      if (d < 40) continue            // stationary => skip
    }
    pts.push([r.x, r.y])
    prev = [r.x, r.y]
  }
  return pts
}

/** Rotate real-world (x east, y north) into screen space (y down). */
export function project([x, y], rotation = 0) {
  // Un-rotated screen frame: north is up.
  let sx = x, sy = -y
  switch (((rotation % 360) + 360) % 360) {
    case 90:  return [-sy, sx]
    case 180: return [-sx, -sy]
    case 270: return [sy, -sx]
    default:  return [sx, sy]
  }
}

/** Bounding box of projected points, padded. */
export function bounds(points, rotation = 0, pad = 400) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
  for (const p of points) {
    const [sx, sy] = project(p, rotation)
    if (sx < minX) minX = sx
    if (sx > maxX) maxX = sx
    if (sy < minY) minY = sy
    if (sy > maxY) maxY = sy
  }
  return {
    x: minX - pad, y: minY - pad,
    w: (maxX - minX) + pad * 2,
    h: (maxY - minY) + pad * 2,
  }
}

/** SVG path data for a closed outline. */
export function pathData(points, rotation = 0) {
  if (!points.length) return ''
  return points
    .map((p, i) => {
      const [sx, sy] = project(p, rotation)
      return `${i ? 'L' : 'M'}${sx.toFixed(0)} ${sy.toFixed(0)}`
    })
    .join(' ') + ' Z'
}
